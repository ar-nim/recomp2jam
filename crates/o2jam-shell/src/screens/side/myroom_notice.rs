/// One MyRoom one-OK sheet: each variant names the pinned exe source
/// for its message and carries only the values the exe interpolates.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MyRoomNotice {
    /// MESSENGER: no server connection (file `0x247dc0`).
    MessengerUnavailable,
    /// MESSENGER: info loading (file `0x247e08`).
    MessengerLoading,
    /// CONFERENCE: modal 20 has no pinned caption; art only.
    Conference,
    /// MESSENGER: modal 21 has no pinned caption; art only.
    MessengerModal,
    /// WEBAVATAR: the helper's copy at file `0x2491e0`.
    WebAvatar,
    /// 5031 success: nickname old → new (file `0x248d60`).
    NicknameChanged { old: String, new: String },
    /// 5031 error -97 (file `0x248d20`).
    NicknameRetry,
    /// 5033 verdict 0: available nickname (file `0x248da0`).
    NicknameAvailable { name: String },
    /// 5033 verdict 1 (file `0x245258`).
    NicknameUnavailable,
    /// 5035 success (file `0x248e60`).
    PenaltyCleared,
    /// 5035 error -98 (file `0x248e10`).
    PenaltyRetry,
    /// 5037 success: bag slots before → after (file `0x248f08`).
    BagExpanded { after: i32 },
    /// 5037 error -96 (file `0x248ec0`).
    BagRetry,
    /// 5039 error -95 (file `0x248f40`).
    BagSortRetry,
    /// 5024 item-gift failure (file `0x2492dc`).
    GiftItemFailure,
    /// 5024 music-gift failure (file `0x2492ac`).
    GiftMusicFailure,
    /// NOTICE board: staged board text (content writer OPEN; the
    /// variant carries only the staged bytes).
    NoticeBoard { text: String },
    /// Well press with no owned id (file `0x2491f4`).
    WornWellMiss,
    /// Vacate with no selection (file `0x2491c0`).
    VacateNoSelection,
    /// Vacate of a default item (file `0x248acc`).
    VacateDefault,
    /// 5024 item-gift success: moved to MyBag (file `0x2492b0`).
    GiftItemSuccess,
    /// 5024 music-gift success: song added (file `0x249280`).
    GiftMusicSuccess,
    /// 5024 item gift landed (file `0x249218`).
    GiftItemMoved,
    /// 5024 music gift landed (file `0x249240`).
    GiftMusicMoved,
}

fn ink_template(template: &[u8], parts: &[&[u8]]) -> Vec<u8> {
    let mut message = Vec::with_capacity(template.len());
    let mut index = 0;
    let mut part = 0;
    while index < template.len() {
        if template[index] == b'%'
            && index + 1 < template.len()
            && matches!(template[index + 1], b's' | b'd')
        {
            if let Some(value) = parts.get(part) {
                message.extend_from_slice(value);
                part += 1;
            }
            index += 2;
        } else {
            message.push(template[index]);
            index += 1;
        }
    }
    message
}

impl MyRoomNotice {
    /// CP949 message bytes for the one-OK sheet. Name fields arrive as
    /// UTF-8 wire strings; the exe's legacy name encoding on those two
    /// interpolations stays OPEN, but digits and fixed copy are exact.
    #[must_use]
    pub fn message(&self) -> Vec<u8> {
        match self {
            Self::MessengerUnavailable => MESSENGER_UNAVAILABLE.to_vec(),
            Self::MessengerLoading => MESSENGER_LOADING.to_vec(),
            Self::Conference | Self::MessengerModal => Vec::new(),
            Self::WebAvatar => WEB_AVATAR.to_vec(),
            Self::NicknameChanged { old, new } => {
                ink_template(NICKNAME_CHANGED, &[old.as_bytes(), new.as_bytes()])
            }
            Self::NicknameRetry => NICKNAME_RETRY.to_vec(),
            Self::NicknameAvailable { name } => {
                ink_template(NICKNAME_AVAILABLE, &[name.as_bytes()])
            }
            Self::NicknameUnavailable => NICKNAME_UNAVAILABLE.to_vec(),
            Self::PenaltyCleared => PENALTY_CLEARED.to_vec(),
            Self::PenaltyRetry => PENALTY_RETRY.to_vec(),
            Self::BagExpanded { after } => {
                let before = after.saturating_sub(30).to_string();
                ink_template(
                    BAG_EXPANDED,
                    &[before.as_bytes(), after.to_string().as_bytes()],
                )
            }
            Self::BagRetry => BAG_RETRY.to_vec(),
            Self::BagSortRetry => BAGSORT_RETRY.to_vec(),
            Self::GiftItemFailure => GIFT_ITEM_FAILURE.to_vec(),
            Self::GiftMusicFailure => GIFT_MUSIC_FAILURE.to_vec(),
            Self::GiftItemMoved => GIFT_ITEM_MOVED.to_vec(),
            Self::GiftMusicMoved => GIFT_MUSIC_MOVED.to_vec(),
            Self::NoticeBoard { text } => text.as_bytes().to_vec(),
            Self::WornWellMiss => WORN_WELL_MISS.to_vec(),
            Self::VacateNoSelection => VACATE_NO_SELECTION.to_vec(),
            Self::VacateDefault => VACATE_DEFAULT.to_vec(),
            Self::GiftItemSuccess => GIFT_ITEM_SUCCESS.to_vec(),
            Self::GiftMusicSuccess => GIFT_MUSIC_SUCCESS.to_vec(),
        }
    }
}

